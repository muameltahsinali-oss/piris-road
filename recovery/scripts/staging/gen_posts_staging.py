"""Regenerate content/posts.ts from the staging site (newer than the backup).

EN body   : WordPress REST API content.rendered
AR body   : the .post-details-content block of the /ar/ page (TranslatePress
            output) — only kept when it is actually translated
Titles/AR : aligned EN/AR pairs harvested by align_ar.py
"""
import sys, os, re, json, html
from lxml import html as LH

sys.stdout.reconfigure(encoding="utf-8")
BASE = os.path.dirname(os.path.abspath(__file__))
ST = os.path.join(BASE, "staging")
OUT = r"C:\Users\omlsa\Desktop\piris_road\content\posts.ts"

posts_api = json.load(open(os.path.join(ST, "posts.json"), encoding="utf-8"))
pairs = json.load(open(os.path.join(BASE, "staging_ar_pairs.json"), encoding="utf-8"))

FEATURED = {
    "logistics-that-lead-forward-introducing-piris-road": "/blog/logistics-new-era.webp",
    "the-impact-of-taxes-on-the-iraqi-market-a-traders-perspective": "/blog/iraqi-market-taxes.webp",
    "iraqs-asycuda-revolution-what-it-means-for-logistics-and-trade": "/blog/asycuda.webp",
    "how-to-choose-the-right-freight-mode-for-your-international-shipments": "/blog/freight-mode.webp",
}
INLINE = [(re.compile(r"https?://[^\"'\s]+/wp-content/uploads/2026/05/3-1[^\"'\s]*\.jpg"), "/blog/logistics-new-era.webp")]
ARABIC = re.compile(r"[\u0600-\u06FF]")


def clean(body):
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    for rx, repl in INLINE:
        body = rx.sub(repl, body)
    # drop responsive srcset/sizes pointing at the staging host
    body = re.sub(r'\s(srcset|sizes)="[^"]*"', "", body)
    body = re.sub(r'\s+data-(start|end)="\d+"', "", body)
    body = re.sub(r'\sclass="wp-image-\d+"', "", body)
    body = body.replace("https://seashell-whale-108794.hostingersite.com", "")
    body = re.sub(r'<h2 class="wp-block-heading">\s*</h2>', "", body)
    body = re.sub(r'\s?class="[^"]*translation-block[^"]*"', "", body)
    body = re.sub(r"\n{3,}", "\n\n", body).strip()
    return body


def ar_body(slug):
    path = os.path.join(ST, slug + "_ar.html")
    if not os.path.exists(path):
        return ""
    doc = LH.parse(path).getroot()
    box = doc.xpath("//div[contains(@class,'post-details-content')]")
    if not box:
        return ""
    skip = ("tz-thumb", "item-meta")
    inner = "".join(
        LH.tostring(c, encoding="unicode", with_tail=False)
        for c in box[0]
        if not any(k in (c.get("class") or "") for k in skip)
    )
    text = re.sub(r"<[^>]+>", " ", inner)
    arabic_ratio = len(ARABIC.findall(text)) / max(1, len(re.findall(r"\w", text)))
    return clean(inner) if arabic_ratio > 0.5 else ""


def text_of(h):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", h))).strip()


out = []
for p in posts_api:
    slug = p["slug"]
    title = html.unescape(p["title"]["rendered"])
    terms = p.get("_embedded", {}).get("wp:term", [])
    cats = [html.unescape(t["name"]) for g in terms for t in g if t["taxonomy"] == "category"]
    tags = [html.unescape(t["name"]) for g in terms for t in g if t["taxonomy"] == "post_tag"]
    body = clean(p["content"]["rendered"])
    excerpt = text_of(p["excerpt"]["rendered"]).replace(" [&hellip;]", "").replace("[…]", "").strip()
    bar = ar_body(slug)
    ex_ar = ""
    if bar:
        m = re.search(r"<p[^>]*>(.*?)</p>", bar, re.S)
        ex_ar = text_of(m.group(1)) if m else ""
    out.append(
        {
            "slug": slug,
            "title": title,
            "titleAr": pairs.get(title, ""),
            "date": p["date"][:10],
            "modified": p["modified"][:10],
            "category": cats[0] if cats and cats[0] != "Uncategorized" else "",
            "tags": tags,
            "image": FEATURED[slug],
            "excerpt": excerpt,
            "excerptAr": ex_ar,
            "body": body,
            "bodyAr": bar,
        }
    )

ts = """/**
 * Blog posts — generated from the STAGING site (seashell-whale-108794), which is
 * newer than the .wpress backup:
 *  - "Logistics That Lead Forward: Introducing PIRIS ROAD" was added (May 2026);
 *  - the backup's Škoda-logo post (WP id 3898) was rewritten in place as
 *    "Iraq's ASYCUDA Revolution";
 *  - two posts got new featured images.
 *
 * English bodies come from the WordPress REST API. Arabic bodies are the
 * TranslatePress output of each /ar/ page, kept only where the post was really
 * translated. An empty `bodyAr` means the live site showed English there too.
 * Generated by gen_posts_staging.py — do not hand-edit.
 */

export type Post = {
  slug: string;
  title: string;
  titleAr: string;
  /** ISO date (YYYY-MM-DD). */
  date: string;
  modified: string;
  category: string;
  tags: string[];
  image: string;
  excerpt: string;
  excerptAr: string;
  /** Raw HTML body. */
  body: string;
  bodyAr: string;
};

export const posts: Post[] = %s;

export const getPost = (slug: string) => posts.find((p) => p.slug === slug);

/** Every category the blog sidebar listed, with its post count. */
export const blogCategories = [
  'Customs & Trade Compliance',
  'Cold Chain & Medical Logistics',
  'Industry Solutions',
  'Freight Forwarding & Transport',
  'Logistics Insights',
  'Project Cargo & Heavy Lift',
].map((name) => ({ name, count: posts.filter((p) => p.category === name).length }));

export const popularTags = Array.from(new Set(posts.flatMap((p) => p.tags))).sort((a, b) =>
  a.localeCompare(b),
);
""" % json.dumps(out, ensure_ascii=False, indent=2)

open(OUT, "w", encoding="utf-8").write(ts)
for o in out:
    print("%-66s %s cat=%-30s en=%5d ar=%5d titleAr=%s" % (o["slug"][:66], o["date"], o["category"], len(o["body"]), len(o["bodyAr"]), bool(o["titleAr"])))
